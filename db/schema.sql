-- ExpensePilot D01 schema
-- 4 张核心表：employees / budgets / policies / reimbursements
-- 适用：Supabase Postgres 或本地 pgvector/pgvector:pg16

create extension if not exists vector;

create table if not exists employees (
    id            bigint generated by default as identity primary key,
    employee_no   text not null unique,
    name          text not null,
    department    text not null,
    level         text not null default 'P5',
    city          text not null default '广州',
    created_at    timestamptz not null default now()
);

create table if not exists budgets (
    id            bigint generated by default as identity primary key,
    department    text not null,
    period        text not null,                 -- YYYY-MM
    category      text not null check (category in ('transport', 'hotel', 'meal', 'other')),
    amount_limit  numeric(12, 2) not null check (amount_limit >= 0),
    amount_used   numeric(12, 2) not null default 0 check (amount_used >= 0),
    unique (department, period, category)
);

create table if not exists policies (
    id             bigint generated by default as identity primary key,
    policy_no      text not null unique,
    title          text not null,
    category       text not null,
    content        text not null,
    effective_from date not null default current_date,
    effective_to   date,
    source         text,
    created_at     timestamptz not null default now()
);

create table if not exists reimbursements (
    id            bigint generated by default as identity primary key,
    employee_id   bigint not null references employees(id),
    trip_city     text not null,
    start_date    date not null,
    end_date      date not null,
    category      text not null check (category in ('transport', 'hotel', 'meal', 'other')),
    amount        numeric(12, 2) not null check (amount > 0),
    invoice_no    text,
    invoice_date  date,
    status        text not null default 'draft'
                  check (status in ('draft', 'pending', 'approved', 'rejected')),
    voucher_json  jsonb,
    created_at    timestamptz not null default now(),
    check (end_date >= start_date)
);

create index if not exists idx_reimbursements_employee on reimbursements (employee_id);
create index if not exists idx_reimbursements_status on reimbursements (status);
create index if not exists idx_budgets_dept_period on budgets (department, period);

comment on table employees is '员工与部门/职级，合成数据';
comment on table budgets is '部门月度预算，按费用类型拆分';
comment on table policies is '财务制度条款，D02 会按条款切分入向量库';
comment on table reimbursements is '报销单，voucher_json 存 Agent 生成的凭证草稿';
